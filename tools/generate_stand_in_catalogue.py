# Finish is Catalogue metadata only in V1 (design-decisions.md §8). Which finishes a Shade is sold
# in varies in real ranges, so it varies here too — a UI that only ever sees the same three would
# not prove it renders the field at all.
FINISH_SETS = (
    ("matte", "satin"),
    ("matte", "satin", "gloss"),
    ("satin",),
    ("matte",),
    ("satin", "gloss"),
)

# Shade Codes carry the family in their leading digits, which is what a real fandeck does — the
# Dealer learns that the 4000s are the earth tones.
CODE_PREFIX = "PS"


def _span(start: float, end: float, steps: int) -> list[float]:
    """`steps` evenly spaced values from start to end inclusive. One step returns the midpoint."""

    if steps == 1:
        return [(start + end) / 2]
    stride = (end - start) / (steps - 1)
    return [start + stride * index for index in range(steps)]


def _hue_span(start_degrees: float, end_degrees: float, steps: int) -> list[float]:
    """Hue angles across a band, taking the short way round when the band crosses 0°.

    Pinks sit either side of 0° (350° to 20°), so treating the band as a plain numeric range would
    walk the long way through every other hue in the wheel.
    """

    if end_degrees < start_degrees:
        end_degrees += 360
    return [angle % 360 for angle in _span(start_degrees, end_degrees, steps)]


def build_shades() -> list[dict]:
    shades: list[dict] = []

    for family_index, (family, hues, lightness, chroma, rows, columns) in enumerate(FAMILIES, 1):
        nouns = NOUNS[family]
        serial = 0

        # Lightness down the rows, hue and strength across the columns: one page of a fandeck.
        for lightness_value in _span(lightness[1], lightness[0], rows):
            hue_angles = _hue_span(hues[0], hues[1], columns)
            chromas = _span(chroma[0], chroma[1], columns)

            for column in range(columns):
                serial += 1
                hue_radians = math.radians(hue_angles[column])
                chroma_value = chromas[column]

                # A dark shade cannot also be weak and still read as its family, and a very light
                # one cannot be strong — pale colours are pale because there is little pigment.
                # Scaling chroma by lightness is what keeps the extremes of each page believable.
                chroma_value *= 0.55 + 0.45 * (lightness_value / 100)

                shades.append(
                    {
                        "shade_code": f"{CODE_PREFIX}-{family_index * 1000 + serial}",
                        "name": f"{MODIFIERS[(serial - 1) // len(nouns) % len(MODIFIERS)]} "
                        f"{nouns[(serial - 1) % len(nouns)]}",
                        "shade_family": family,
                        "lab": {
                            "l": round(lightness_value, 2),
                            "a": round(chroma_value * math.cos(hue_radians), 2),
                            "b": round(chroma_value * math.sin(hue_radians), 2),
                        },
                        "finishes": list(FINISH_SETS[serial % len(FINISH_SETS)]),
                    }
                )

    return shades


def build_catalogue() -> dict:
    shades = build_shades()

    # A duplicate Shade Code would be a silent fault: the loader treats the code as unique, so two
    # rows sharing one would make a Shade unreachable rather than error.
    codes = [shade["shade_code"] for shade in shades]
    duplicates = {code for code in codes if codes.count(code) > 1}
    if duplicates:
        raise SystemExit(f"generated duplicate Shade Codes: {sorted(duplicates)}")

    # Names are not required to be unique by the format, but a fixture with repeats would make a
    # name search look broken, so the generator holds itself to a higher standard than the loader.
    names = [shade["name"] for shade in shades]
    repeated = {name for name in names if names.count(name) > 1}
    if repeated:
        raise SystemExit(f"generated duplicate Shade names: {sorted(repeated)}")

    return {
        "catalogue_id": CATALOGUE_ID,
        "catalogue_name": CATALOGUE_NAME,
        "version": VERSION,
        "source": SOURCE,
        "colour_space": {"space": "CIELAB", "reference_white": "D65", "observer": "2"},
        "shades": shades,
    }


def serialise(catalogue: dict) -> str:
    # Newline-terminated, LF, two-space indent: a text file that behaves the same on both platforms
    # and produces a readable diff when the generator is retuned.
    return json.dumps(catalogue, indent=2, ensure_ascii=False) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed file matches what this script generates; write nothing",
    )
    arguments = parser.parse_args()

    expected = serialise(build_catalogue())

    if arguments.check:
        if not OUTPUT_PATH.exists():
            raise SystemExit(f"{OUTPUT_PATH} is missing. Run this script without --check.")
        if OUTPUT_PATH.read_text(encoding="utf-8") != expected:
            raise SystemExit(
                f"{OUTPUT_PATH} does not match the generator. "
                "Re-run this script without --check and commit the result."
            )
        print(f"{OUTPUT_PATH.name} matches the generator.")
        return

    OUTPUT_PATH.write_text(expected, encoding="utf-8", newline="\n")
    count = expected.count('"shade_code"')
    print(f"Wrote {count} Shades to {OUTPUT_PATH}", file=sys.stderr)


if __name__ == "__main__":
    main()
