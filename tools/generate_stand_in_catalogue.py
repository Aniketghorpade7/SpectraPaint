"""
Generate the public stand-in Catalogue file, by sampling the Lab space.

    python tools/generate_stand_in_catalogue.py            # write the file
    python tools/generate_stand_in_catalogue.py --check     # verify the committed file matches

The Catalogue this project ships against is Arun Paint Industries' measured values, which have not
arrived yet. Everything downstream — search, Shade Family browsing, and above all the claim that a
thousand-plus Shade Catalogue scrolls smoothly — needs a file of realistic size today.

Why generated rather than borrowed: a real manufacturer's fandeck is their data, and committing one
would put a redistribution question in the repository for values we are going to replace anyway.
Sampling the Lab space ourselves has no licence, and gives something better for testing: Shades
spread evenly across the families a dealer browses, at a size we choose.

What this is *not* is accurate. These are plausible paint colours, not measured ones. Accuracy
evaluation waits for the real data — see docs/design-decisions.md §7.

Deterministic: no randomness anywhere, so the same input always produces byte-identical output and
`--check` is meaningful in CI.
"""

